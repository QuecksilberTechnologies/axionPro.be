-- ============================================================================
-- SECTION 6
-- HOST DEFAULT EMAIL CONFIG MODULE OPERATION MAPPING
-- ============================================================================
--
-- Existing Operation master reuse hoga.
--
-- Supported operation names:
--
-- View / Read
-- Create / Add
-- Update / Edit
-- Delete
--
-- ============================================================================

INSERT INTO axionpro."ModuleOperationMapping"
(
    "ModuleId",

    "OperationId",

    "IsCommonItem",

    "IsOperational",

    "Priority",

    "Remark",

    "IsActive",

    "AddedById",

    "AddedDateTime"
)

SELECT

    module."Id",

    operation."Id",

    FALSE,

    TRUE,

    CASE

        WHEN LOWER(BTRIM(operation."OperationName"))
             IN ('view', 'read')
            THEN 1

        WHEN LOWER(BTRIM(operation."OperationName"))
             IN ('create', 'add')
            THEN 2

        WHEN LOWER(BTRIM(operation."OperationName"))
             IN ('update', 'edit')
            THEN 3

        WHEN LOWER(BTRIM(operation."OperationName"))
             = 'delete'
            THEN 4

        ELSE 10

    END,

    CASE

        WHEN LOWER(BTRIM(operation."OperationName"))
             IN ('view', 'read')

            THEN
            'View Host default email configuration.'

        WHEN LOWER(BTRIM(operation."OperationName"))
             IN ('create', 'add')

            THEN
            'Create Host default email configuration.'

        WHEN LOWER(BTRIM(operation."OperationName"))
             IN ('update', 'edit')

            THEN
            'Update Host default email configuration.'

        WHEN LOWER(BTRIM(operation."OperationName"))
             = 'delete'

            THEN
            'Delete Host default email configuration.'

        ELSE
            'Host default email configuration operation.'

    END,

    TRUE,

    1,

    CURRENT_TIMESTAMP

FROM axionpro."Module" module

INNER JOIN axionpro."Operation" operation

    ON LOWER(BTRIM(operation."OperationName"))

       IN
       (
           'view',
           'read',
           'create',
           'add',
           'update',
           'edit',
           'delete'
       )

WHERE module."ModuleCode"
      = 'HOST_DEFAULT_EMAIL_CONFIG'

  AND operation."IsActive"
      = TRUE

  AND NOT EXISTS
  (
      SELECT 1

      FROM axionpro."ModuleOperationMapping"
          existingMapping

      WHERE existingMapping."ModuleId"
            = module."Id"

        AND existingMapping."OperationId"
            = operation."Id"
  );


