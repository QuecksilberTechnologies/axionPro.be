-- SMTP PORT VALIDATION
-- ============================================================================

DO
$$
BEGIN

    IF NOT EXISTS
    (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'CK_DefaultEmailConfig_SmtpPort'
          AND conrelid = 'axionpro."DefaultEmailConfig"'::regclass
