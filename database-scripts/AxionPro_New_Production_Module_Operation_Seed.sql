-- SECTION 10
-- SAFE AUTO-INCREMENT / IDENTITY SYNCHRONIZATION
-- ============================================================================
--
-- IMPORTANT:
--
-- Empty table:
--     next ID = 1
--
-- Existing table:
--     next ID = MAX(Id) + 1
--
-- Host authorization tables are intentionally rebuilt above, so their
-- sequences are restarted from the canonical seed rows; other tables retain
-- the normal MAX(Id) + 1 behavior.
-- ============================================================================

DO
$$
DECLARE

    sequence_name TEXT;

    maximum_id BIGINT;

BEGIN


    -- ========================================================================
    -- DefaultEmailConfig
    -- ========================================================================

    sequence_name :=
        pg_get_serial_sequence
        (
            'axionpro."DefaultEmailConfig"',
            'Id'
        );


    IF sequence_name IS NOT NULL THEN

        SELECT COALESCE(MAX("Id"), 0)

        INTO maximum_id

        FROM axionpro."DefaultEmailConfig";


        IF maximum_id = 0 THEN

            PERFORM setval
            (
                sequence_name::regclass,
                1,
                FALSE
            );

        ELSE

            PERFORM setval
            (
                sequence_name::regclass,
                maximum_id,
                TRUE
            );

        END IF;

    END IF;



    -- ========================================================================
    -- Module
    -- ========================================================================

    sequence_name :=
        pg_get_serial_sequence
        (
            'axionpro."Module"',
            'Id'
        );


    IF sequence_name IS NOT NULL THEN

        SELECT COALESCE(MAX("Id"), 0)

        INTO maximum_id

        FROM axionpro."Module";


        IF maximum_id = 0 THEN

            PERFORM setval
            (
                sequence_name::regclass,
                1,
                FALSE
            );

        ELSE

            PERFORM setval
            (
                sequence_name::regclass,
                maximum_id,
                TRUE
            );

        END IF;

    END IF;



    -- ========================================================================
    -- ModuleOperationMapping
    -- ========================================================================

    sequence_name :=
        pg_get_serial_sequence
        (
            'axionpro."ModuleOperationMapping"',
            'Id'
        );


    IF sequence_name IS NOT NULL THEN

        SELECT COALESCE(MAX("Id"), 0)

        INTO maximum_id

        FROM axionpro."ModuleOperationMapping";


        IF maximum_id = 0 THEN

            PERFORM setval
            (
                sequence_name::regclass,
                1,
                FALSE
            );

        ELSE

            PERFORM setval
            (
                sequence_name::regclass,
                maximum_id,
                TRUE
            );

        END IF;

    END IF;


    -- ========================================================================
    -- HostRole
    -- ========================================================================

    sequence_name := pg_get_serial_sequence('axionpro."HostRole"', 'Id');

    IF sequence_name IS NOT NULL THEN
        SELECT COALESCE(MAX("Id"), 0)
        INTO maximum_id
        FROM axionpro."HostRole";

        PERFORM setval(
            sequence_name::regclass,
            CASE WHEN maximum_id = 0 THEN 1 ELSE maximum_id END,
            maximum_id <> 0);
    END IF;


    -- ========================================================================
    -- HostUser
    -- ========================================================================

    sequence_name := pg_get_serial_sequence('axionpro."HostUser"', 'Id');

    IF sequence_name IS NOT NULL THEN
        SELECT COALESCE(MAX("Id"), 0)
        INTO maximum_id
        FROM axionpro."HostUser";

        PERFORM setval(
            sequence_name::regclass,
            CASE WHEN maximum_id = 0 THEN 1 ELSE maximum_id END,
            maximum_id <> 0);
    END IF;


    -- ========================================================================
    -- HostRoleModuleAndPermission
    -- ========================================================================

    sequence_name := pg_get_serial_sequence('axionpro."HostRoleModuleAndPermission"', 'Id');

    IF sequence_name IS NOT NULL THEN
        SELECT COALESCE(MAX("Id"), 0)
        INTO maximum_id
        FROM axionpro."HostRoleModuleAndPermission";

        PERFORM setval(
            sequence_name::regclass,
            CASE WHEN maximum_id = 0 THEN 1 ELSE maximum_id END,
            maximum_id <> 0);
    END IF;

END;
$$;


