        AS "OperationId",

    operation."OperationName",

    mapping."Priority",

    mapping."IsCommonItem",

    mapping."IsOperational",

    mapping."Remark",

    mapping."IsActive"

FROM axionpro."ModuleOperationMapping"
    mapping

INNER JOIN axionpro."Module"
    module

    ON module."Id"
       = mapping."ModuleId"

INNER JOIN axionpro."Operation"
    operation

    ON operation."Id"
       = mapping."OperationId"

WHERE module."ModuleCode"
      IN
      (
          'HOST_DEFAULT_EMAIL_CONFIG',
          'HOST_TENANT_EMAIL_CONFIG',
          'TENANT_EMAIL_CONFIG',
          'HOST_EMAIL_TEMPLATE',
          'HOST_DEVICE_SETUP',
          'TENANT_DEVICE_SETUP',
          'HOST_INITIAL_DEVICE_CONFIGURATION',
          'TENANT_DEVICE_CONFIGURATION',
          'EMP_PASSWORD_MANAGEMENT'
      )

ORDER BY

    module."ModuleScope",

    module."ModuleCode",

    mapping."Priority",

    operation."OperationName";


