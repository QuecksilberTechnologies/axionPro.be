    VALUES
        ('View',   'View permitted records and details.', 4, 'eye'),
        ('Create', 'Create a permitted record or queue a new request.', 1, 'plus-circle'),
        ('Update', 'Update a permitted record or apply an approved change.', 2, 'pencil-square'),
