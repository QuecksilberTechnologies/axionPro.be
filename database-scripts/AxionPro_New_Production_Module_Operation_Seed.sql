-- ============================================================================
-- SECTION 9
-- PRODUCTION VALIDATION
-- ============================================================================
--
-- Agar required module ya operation mapping create nahi hui
-- to transaction COMMIT nahi hogi.
-- ============================================================================

DO
$$
DECLARE

    host_module_count INTEGER;

    tenant_module_count INTEGER;

    host_mapping_count INTEGER;

    tenant_mapping_count INTEGER;

BEGIN

    SELECT COUNT(*)

    INTO host_module_count

    FROM axionpro."Module"

    WHERE "ModuleCode"
          = 'HOST_DEFAULT_EMAIL_CONFIG';


    SELECT COUNT(*)

    INTO tenant_module_count

    FROM axionpro."Module"

    WHERE "ModuleCode"
          = 'TENANT_EMAIL_CONFIG';


    IF host_module_count <> 1 THEN

        RAISE EXCEPTION
        'Expected exactly one HOST_DEFAULT_EMAIL_CONFIG module. Found: %',
        host_module_count;

    END IF;


    IF tenant_module_count <> 1 THEN

        RAISE EXCEPTION
        'Expected exactly one TENANT_EMAIL_CONFIG module. Found: %',
        tenant_module_count;

    END IF;


    SELECT COUNT(*)

    INTO host_mapping_count

    FROM axionpro."ModuleOperationMapping"
        mapping

    INNER JOIN axionpro."Module"
        module

        ON module."Id"
           = mapping."ModuleId"

    WHERE module."ModuleCode"
          = 'HOST_DEFAULT_EMAIL_CONFIG'

      AND mapping."IsActive"
          = TRUE;


    SELECT COUNT(*)

    INTO tenant_mapping_count

    FROM axionpro."ModuleOperationMapping"
        mapping

    INNER JOIN axionpro."Module"
        module

        ON module."Id"
           = mapping."ModuleId"

    WHERE module."ModuleCode"
          = 'TENANT_EMAIL_CONFIG'

      AND mapping."IsActive"
          = TRUE;


    IF host_mapping_count = 0 THEN

        RAISE EXCEPTION
        'No CRUD Operation mapping found for HOST_DEFAULT_EMAIL_CONFIG. Check Operation master data.';

    END IF;


    IF tenant_mapping_count = 0 THEN

        RAISE EXCEPTION
        'No CRUD Operation mapping found for TENANT_EMAIL_CONFIG. Check Operation master data.';

    END IF;

END;
$$;


-- ============================================================================
-- SECTION 10
-- SAFE AUTO-INCREMENT / IDENTITY SYNCHRONIZATION
-- ============================================================================
--
-- IMPORTANT:
--
-- Empty table:
--     next ID = 1
--
-- Existing table:
--     next ID = MAX(Id) + 1
--
-- Existing production IDs kabhi backward reset nahi honge.
-- ============================================================================

DO
$$
DECLARE

    sequence_name TEXT;

    maximum_id BIGINT;

BEGIN


    -- ========================================================================
    -- DefaultEmailConfig
    -- ========================================================================

    sequence_name :=
        pg_get_serial_sequence
        (
            'axionpro."DefaultEmailConfig"',
            'Id'
        );


    IF sequence_name IS NOT NULL THEN

        SELECT COALESCE(MAX("Id"), 0)

        INTO maximum_id

        FROM axionpro."DefaultEmailConfig";


        IF maximum_id = 0 THEN

            PERFORM setval
            (
                sequence_name::regclass,
                1,
                FALSE
            );

        ELSE

            PERFORM setval
            (
                sequence_name::regclass,
                maximum_id,
                TRUE
            );

        END IF;

    END IF;



    -- ========================================================================
    -- Module
    -- ========================================================================

    sequence_name :=
        pg_get_serial_sequence
        (
            'axionpro."Module"',
            'Id'
        );


    IF sequence_name IS NOT NULL THEN

        SELECT COALESCE(MAX("Id"), 0)

        INTO maximum_id

        FROM axionpro."Module";


        IF maximum_id = 0 THEN

            PERFORM setval
            (
                sequence_name::regclass,
                1,
                FALSE
            );

        ELSE

            PERFORM setval
            (
                sequence_name::regclass,
                maximum_id,
                TRUE
            );

        END IF;

    END IF;



    -- ========================================================================
    -- ModuleOperationMapping
    -- ========================================================================

    sequence_name :=
        pg_get_serial_sequence
        (
            'axionpro."ModuleOperationMapping"',
            'Id'
        );


    IF sequence_name IS NOT NULL THEN

        SELECT COALESCE(MAX("Id"), 0)

        INTO maximum_id

        FROM axionpro."ModuleOperationMapping";


        IF maximum_id = 0 THEN

            PERFORM setval
            (
                sequence_name::regclass,
                1,
                FALSE
            );

        ELSE

            PERFORM setval
            (
                sequence_name::regclass,
                maximum_id,
                TRUE
            );

        END IF;

    END IF;

END;
$$;


