-- ============================================================================
-- SECTION 3 : SEED DEFAULT EMAIL CONFIGURATION
-- ============================================================================
--
-- Latest complete active TenantEmailConfig configuration ko source banaya jayega.
--
-- Isliye production SQL me:
-- Password
-- Secret
-- SMTP Username
--
-- manually paste nahi karna padega.
-- ============================================================================

DO
$$
BEGIN

    INSERT INTO axionpro."DefaultEmailConfig"
    (
        "ConfigName",
        "SmtpHost",
        "SmtpPort",
        "SmtpUsername",
        "SmtpPasswordEncrypted",
        "FromEmail",
        "FromName",
        "IsActive",
        "IsDefault",
        "SecrateKey"
    )

    SELECT

        'DEFAULT_REGISTRATION_SMTP',

        BTRIM(configuration."SmtpHost"),

        configuration."SmtpPort",

        BTRIM(configuration."SmtpUsername"),

        COALESCE
        (
            NULLIF
            (
                BTRIM(configuration."SmtpPasswordEncrypted"),
                ''
            ),

            NULLIF
            (
                BTRIM(configuration."SecrateKey"),
                ''
            )
        ),

        BTRIM(configuration."FromEmail"),

        BTRIM(configuration."FromName"),

        TRUE,

        NOT EXISTS
        (
            SELECT 1

            FROM axionpro."DefaultEmailConfig"
                existingDefault

            WHERE existingDefault."IsDefault" = TRUE
        ),

        COALESCE
        (
            NULLIF
            (
                BTRIM(configuration."SecrateKey"),
                ''
            ),

            NULLIF
            (
                BTRIM(configuration."SmtpPasswordEncrypted"),
                ''
            )
        )

    FROM axionpro."TenantEmailConfig"
        configuration

    WHERE configuration."IsActive" = TRUE

      AND NULLIF
          (
              BTRIM(configuration."SmtpHost"),
              ''
          ) IS NOT NULL

      AND configuration."SmtpPort"
          BETWEEN 1 AND 65535

      AND NULLIF
          (
              BTRIM(configuration."SmtpUsername"),
              ''
          ) IS NOT NULL

      AND COALESCE
          (
              NULLIF
              (
                  BTRIM(configuration."SmtpPasswordEncrypted"),
                  ''
              ),

              NULLIF
              (
                  BTRIM(configuration."SecrateKey"),
                  ''
              )
          ) IS NOT NULL

      AND NULLIF
          (
              BTRIM(configuration."FromEmail"),
              ''
          ) IS NOT NULL

      AND NULLIF
          (
              BTRIM(configuration."FromName"),
              ''
          ) IS NOT NULL

    ORDER BY configuration."Id" DESC

    LIMIT 1


    ON CONFLICT ("ConfigName")

    DO UPDATE SET

        "SmtpHost"
            = EXCLUDED."SmtpHost",

        "SmtpPort"
            = EXCLUDED."SmtpPort",

        "SmtpUsername"
            = EXCLUDED."SmtpUsername",

        "SmtpPasswordEncrypted"
            = EXCLUDED."SmtpPasswordEncrypted",

        "FromEmail"
            = EXCLUDED."FromEmail",

        "FromName"
            = EXCLUDED."FromName",

        "IsActive"
            = TRUE,

        "SecrateKey"
            = EXCLUDED."SecrateKey",

        "UpdatedDateTime"
            = CURRENT_TIMESTAMP;


    IF NOT FOUND THEN

        RAISE EXCEPTION
        'No complete active TenantEmailConfig found. DefaultEmailConfig could not be seeded.';

    END IF;

END;
$$;


