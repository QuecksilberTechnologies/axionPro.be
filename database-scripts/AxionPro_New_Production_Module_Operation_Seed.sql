    mapping

INNER JOIN axionpro."Module"
    module

    ON module."Id"
       = mapping."ModuleId"

INNER JOIN axionpro."Operation"
    operation

    ON operation."Id"
       = mapping."OperationId"

WHERE module."ModuleCode"
      IN
      (
          'HOST_DEFAULT_EMAIL_CONFIG',
          'TENANT_EMAIL_CONFIG'
      )

