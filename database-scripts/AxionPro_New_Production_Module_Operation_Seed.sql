                     = 'delete'

                THEN
                'Delete Host default email configuration.'


            WHEN module."ModuleCode"
                 = 'TENANT_EMAIL_CONFIG'

                 AND LOWER(BTRIM(operation."OperationName"))
                     IN ('view', 'read')

