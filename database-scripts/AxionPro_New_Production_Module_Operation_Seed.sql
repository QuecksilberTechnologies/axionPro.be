            WHEN LOWER(BTRIM(operation."OperationName"))
                 IN ('view', 'read')
                THEN 1

            WHEN LOWER(BTRIM(operation."OperationName"))
                 IN ('create', 'add')
                THEN 2

            WHEN LOWER(BTRIM(operation."OperationName"))
                 IN ('update', 'edit')
