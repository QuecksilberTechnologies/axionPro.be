    END IF;

    IF reset_password_mapping_count <> 1 THEN
        RAISE EXCEPTION
            'EMP_PASSWORD_MANAGEMENT mapping validation failed. Expected 1, found %.',
            reset_password_mapping_count;
    END IF;
